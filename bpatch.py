def _detect_format(binary_path: Path) -> str:
    """Return 'ELF', 'PE', or raise a friendly error."""
    try:
        parsed = lief.parse(str(binary_path))
    except Exception as e:
        print(f"[!] Failed to parse {binary_path}: {e}")
        sys.exit(1)
    if parsed is None:
        print(f"[!] LIEF could not parse {binary_path}")
        print(f"    Make sure it is a valid x86-64 ELF or PE binary.")
        sys.exit(1)
    if   isinstance(parsed, lief.ELF.Binary):   return "ELF"
    elif isinstance(parsed, lief.PE.Binary):    return "PE"
    elif isinstance(parsed, lief.MachO.Binary):
        print("[!] Mach-O is not yet supported.")
        sys.exit(1)
    else:
        print(f"[!] Unrecognized binary format: {binary_path}")
        sys.exit(1)


def inject(binary_path: Path, target_va: int, payload_c: Path, out: Path):
    fmt = _detect_format(binary_path)

    print(f"[*] binary:  {binary_path}")
    print(f"[*] format:  {fmt}")
    print(f"[*] target:  0x{target_va:x}")
    print(f"[*] payload: {payload_c}")
    print(f"[*] output:  {out}")
    print()

    if fmt == "ELF": inject_elf(binary_path, target_va, payload_c, out)
    else:            inject_pe (binary_path, target_va, payload_c, out)


def _list_examples():
    """Print available example payloads from the examples/ directory."""
    here     = Path(__file__).parent
    examples = sorted(here.glob("examples/*.c"))
    if not examples:
        print("No example payloads found in examples/")
        return
    print("Available example payloads:")
    print()
    # Group linux vs windows
    linux = [e for e in examples if not e.stem.endswith("_win")]
    win   = [e for e in examples if e.stem.endswith("_win")]
    if linux:
        print("  Linux / ELF (SysV ABI: ARG1=rdi, ARG2=rsi ...)")
        for e in linux:
            # Pull the first comment line as description
            lines = e.read_text(encoding="utf-8").splitlines()
            desc  = next((l.lstrip("/* ").rstrip() for l in lines
                          if l.strip().startswith("*") and len(l.strip()) > 2
                          and not l.strip().startswith("**")), "")
            print(f"    {e.name:30s}  {desc}")
    print()
    if win:
        print("  Windows / PE (MS x64 ABI: ARG1=rcx, ARG2=rdx ...)")
        for e in win:
            lines = e.read_text(encoding="utf-8").splitlines()
            desc  = next((l.lstrip("/* ").rstrip() for l in lines
                          if l.strip().startswith("*") and len(l.strip()) > 2
                          and not l.strip().startswith("**")), "")
            print(f"    {e.name:30s}  {desc}")
    print()


