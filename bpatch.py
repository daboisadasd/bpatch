BPATCH_RT_WIN64_H = r"""
#pragma once
/*
 * bpatch_rt.h - Windows x64 (Microsoft ABI) - generated by bpatch
 *
 * No CRT, no import table entries.  File I/O is resolved at runtime via
 * PEB -> kernel32.dll export table walking.  Works on all Windows versions.
 */

typedef unsigned char       u8;
typedef unsigned short      u16;
typedef unsigned int        u32;
typedef unsigned long long  u64;
typedef long long           i64;
typedef unsigned short      bp_wchar;   /* wchar_t is 2 bytes on Windows */
typedef void *              HANDLE;
#define BP_INVALID_HANDLE   ((HANDLE)(i64)-1)

/*
 * ctx_t - same field layout as Linux version (rax at offset 0).
 * Windows x64 differences: ARG1=rcx, ARG2=rdx, ARG3=r8, ARG4=r9.
 */
typedef struct {
    u64 rax;    u64 rbx;    u64 rcx;    u64 rdx;
    u64 rsi;    u64 rdi;    u64 rbp;
    u64 r8;     u64 r9;     u64 r10;    u64 r11;
    u64 r12;    u64 r13;    u64 r14;    u64 r15;
    u64 rflags;
} ctx_t;

/* Raw registers */
#define RAX    (ctx->rax)
#define RBX    (ctx->rbx)
#define RCX    (ctx->rcx)
#define RDX    (ctx->rdx)
#define RSI    (ctx->rsi)
#define RDI    (ctx->rdi)
#define RBP    (ctx->rbp)
#define R8     (ctx->r8)
#define R9     (ctx->r9)
#define R10    (ctx->r10)
#define R11    (ctx->r11)
#define R12    (ctx->r12)
#define R13    (ctx->r13)
#define R14    (ctx->r14)
#define R15    (ctx->r15)
#define RFLAGS (ctx->rflags)

/* Windows x64: rcx, rdx, r8, r9 */
#define ARG1   (ctx->rcx)
#define ARG2   (ctx->rdx)
#define ARG3   (ctx->r8)
#define ARG4   (ctx->r9)
#define RETVAL (ctx->rax)

#define ARG1_PTR(t)  ((t*)(ctx->rcx))
#define ARG2_PTR(t)  ((t*)(ctx->rdx))
#define ARG3_PTR(t)  ((t*)(ctx->r8))
#define RAX_PTR(t)   ((t*)(ctx->rax))
#define RCX_PTR(t)   ((t*)(ctx->rcx))
#define RDX_PTR(t)   ((t*)(ctx->rdx))

/* -- PEB walking ----------------------------------------------------------- */
/*
 * Walk GS:[0x60] -> PEB -> Ldr -> InLoadOrderModuleList to find a DLL by name,
 * then parse its PE export table to find a named function.
 * No imports needed - resolves entirely from in-memory data structures.
 *
 * PEB (x64):  +0x18 = Ldr (PPEB_LDR_DATA)
 * LDR:        +0x10 = InLoadOrderModuleList.Flink
 * LDTE:       +0x30 = DllBase,  +0x58 = BaseDllName (UNICODE_STRING)
 * UNICODE_STRING: +0 = Length (u16, byte count),  +8 = Buffer (wchar_t*)
 */
static __attribute__((always_inline)) inline
void *_bp_get_module(const bp_wchar *want, int want_bytes) {
    void *peb;
    __asm__ volatile ("movq %%gs:0x60, %0" : "=r"(peb));
    void *ldr   = *(void**)((u8*)peb  + 0x18);
    void *head  = *(void**)((u8*)ldr  + 0x10);  /* Flink = first entry */
    void *cur   = head;
    do {
        u16        len = *(u16      *)((u8*)cur + 0x58);
        bp_wchar  *buf = *(bp_wchar**)((u8*)cur + 0x58 + 8);
        if (len == (u16)want_bytes) {
            int ok = 1;
            for (int i = 0; i < want_bytes/2; i++) {
                bp_wchar a=buf[i], b=want[i];
                if(a>='a'&&a<='z') a-=32;
                if(b>='a'&&b<='z') b-=32;
                if(a!=b){ok=0;break;}
            }
            if (ok) return *(void**)((u8*)cur + 0x30);
        }
        cur = *(void**)cur;  /* Flink */
    } while (cur != head);
    return (void*)0;
}

static __attribute__((always_inline)) inline
int _bp_strcmp(const char *a, const char *b) {
    while(*a && *a==*b){a++;b++;} return *a-*b;
}

/*
 * PE64 export table walk.
 * NT headers:  base[0x3C] = e_lfanew
 * OptHeader64: base + e_lfanew + 0x18
 * DataDir[0]:  OptHeader + 0x70  (Export Directory RVA)
 * Export dir:  +0x14=NumFunctions, +0x18=NumNames,
 *              +0x1C=AddressOfFunctions, +0x20=AddressOfNames,
 *              +0x24=AddressOfNameOrdinals
 */
static __attribute__((always_inline)) inline
void *_bp_get_proc(void *base, const char *name) {
    u8  *b       = (u8*)base;
    u32  lfanew  = *(u32*)(b + 0x3C);
    u32  exp_rva = *(u32*)(b + lfanew + 0x18 + 0x70);
    if (!exp_rva) return (void*)0;
    u8  *exp     = b + exp_rva;
    u32  nnames  = *(u32*)(exp + 0x18);
    u32 *names   = (u32*)(b + *(u32*)(exp + 0x20));
    u16 *ords    = (u16*)(b + *(u32*)(exp + 0x24));
    u32 *funcs   = (u32*)(b + *(u32*)(exp + 0x1C));
    for (u32 i = 0; i < nnames; i++)
        if (_bp_strcmp((char*)(b + names[i]), name) == 0)
            return (void*)(b + funcs[ords[i]]);
    return (void*)0;
}

static __attribute__((always_inline)) inline void *_bp_k32(void) {
    /* "kernel32.dll" as UTF-16LE u16 array - avoids needing wchar_t / stddef.h */
    bp_wchar n[] = {'k','e','r','n','e','l','3','2','.','d','l','l',0};
    return _bp_get_module(n, (int)(sizeof(n) - sizeof(bp_wchar)));
}

/* -- Win32 file I/O ------------------------------------------------------- */
typedef HANDLE (*_PFN_CF)(const char*,u32,u32,void*,u32,u32,HANDLE);
typedef int    (*_PFN_WF)(HANDLE,const void*,u32,u32*,void*);
typedef int    (*_PFN_CH)(HANDLE);

#define _BP_GENERIC_WRITE 0x40000000u
#define _BP_FILE_SHARE_RW 0x03u
#define _BP_CREATE_ALWAYS 2u
#define _BP_OPEN_ALWAYS   4u
#define _BP_FILE_NORMAL   0x80u
#define _BP_APPEND_DATA   0x04u

static inline HANDLE _bp_open_write(const char *path) {
    void *k = _bp_k32(); if(!k) return BP_INVALID_HANDLE;
    _PFN_CF f = (_PFN_CF)_bp_get_proc(k,"CreateFileA"); if(!f) return BP_INVALID_HANDLE;
    return f(path,_BP_GENERIC_WRITE,_BP_FILE_SHARE_RW,(void*)0,_BP_CREATE_ALWAYS,_BP_FILE_NORMAL,(HANDLE)0);
}
static inline HANDLE _bp_open_append(const char *path) {
    void *k = _bp_k32(); if(!k) return BP_INVALID_HANDLE;
    _PFN_CF f = (_PFN_CF)_bp_get_proc(k,"CreateFileA"); if(!f) return BP_INVALID_HANDLE;
    return f(path,_BP_APPEND_DATA,_BP_FILE_SHARE_RW,(void*)0,_BP_OPEN_ALWAYS,_BP_FILE_NORMAL,(HANDLE)0);
}
static inline void _bp_write_close(HANDLE h, const void *d, u32 len) {
    void *k = _bp_k32(); if(!k||h==BP_INVALID_HANDLE) return;
    _PFN_WF wf = (_PFN_WF)_bp_get_proc(k,"WriteFile");
    _PFN_CH cf = (_PFN_CH)_bp_get_proc(k,"CloseHandle");
    u32 wr=0; if(wf) wf(h,d,len,&wr,(void*)0);
    if(cf) cf(h);
}

/* -- Helpers --------------------------------------------------------------- */
static inline u32 bp_strlen(const char *s) { u32 n=0; while(s[n]) n++; return n; }

static inline void dump_bytes(const void *d, u32 len, const char *path) {
    HANDLE h = _bp_open_write(path); _bp_write_close(h, d, len);
}
static inline void dump_append(const void *d, u32 len, const char *path) {
    HANDLE h = _bp_open_append(path); _bp_write_close(h, d, len);
}
static inline void dump_str(const char *s, const char *path)        { dump_bytes(s, bp_strlen(s), path); }
static inline void dump_str_append(const char *s, const char *path) { dump_append(s, bp_strlen(s), path); }
static inline void dump_u64(u64 v, const char *path) {
    char buf[19]; buf[0]='0'; buf[1]='x';
    for(int i=0;i<16;i++){u8 n=(u8)((v>>(60-i*4))&0xF); buf[2+i]=n<10?'0'+n:'a'+(n-10);}
    buf[18]='\n'; dump_append(buf,19,path);
}
static inline void dump_ctx(ctx_t *c, const char *path) { dump_bytes(c,sizeof(ctx_t),path); }

/* NOTE: use  char arr[] = "..."  not  char *p = "..."  for string literals. */
#define DUMP_STR_REG(reg,path)          dump_str((const char*)(u64)(reg),(path))
#define DUMP_BYTES_REG(reg,len,path)    dump_bytes((const void*)(u64)(reg),(u32)(len),(path))
#define LOG_REG(name,reg,path)          do{ char _l[]=name": "; dump_str_append(_l,path); dump_u64((u64)(reg),path); }while(0)
"""


