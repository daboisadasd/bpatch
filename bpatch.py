def main():
    # Force UTF-8 output on Windows so box-drawing / arrows in messages work.
    # This is a no-op on Linux/macOS.
    if platform.system() == "Windows":
        try:
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
            sys.stderr.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass

    ap = argparse.ArgumentParser(
        description="bpatch - static binary injection tool for malware analysis",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
examples:
  # Inject at a function entry and dump the first argument (a string)
  bpatch.py target.exe  --at 0x140001234 --payload dump_string_win.c
  bpatch.py target.elf  --at 0x401234    --payload dump_string.c

  # Log all register values every time a site is hit
  bpatch.py target.exe  --at 0x140001234 --payload log_regs_win.c

  # Force a function to always return 1 (bypass license/anti-debug checks)
  bpatch.py target.exe  --at 0x14000ABCD --payload patch_retval_win.c

  # Dump the runtime header so you can write your own payload
  bpatch.py --dump-header --pe       (Windows)
  bpatch.py --dump-header            (Linux)

  # List available example payloads
  bpatch.py --list
"""
    )
    ap.add_argument("binary",         nargs="?",
                    help="Target binary (.exe or ELF, auto-detected)")
    ap.add_argument("--at",           metavar="ADDR",
                    help="Injection address in hex, including imagebase "
                         "(e.g. 0x140001234 as shown in IDA / x64dbg)")
    ap.add_argument("--payload",      metavar="FILE.c",
                    help="C payload source file (see --list for examples)")
    ap.add_argument("-o", "--output", metavar="OUT",
                    help="Output path (default: <binary>.patched[.exe])")
    ap.add_argument("--dump-header",  action="store_true",
                    help="Write bpatch_rt.h to the current directory and exit")
    ap.add_argument("--pe",           action="store_true",
                    help="Use the Windows/PE runtime header (with --dump-header)")
    ap.add_argument("--list",         action="store_true",
                    help="List available example payloads and exit")
    args = ap.parse_args()

    # ---- info-only modes ----
    if args.list:
        _list_examples()
        return

    if args.dump_header:
        rt, name = (BPATCH_RT_WIN64_H, "bpatch_rt_win64.h") if args.pe \
                   else (BPATCH_RT_LINUX_H, "bpatch_rt.h")
        Path(name).write_text(rt, encoding="utf-8")
        print(f"[+] Written: {Path(name).resolve()}")
        print(f"    Include this in your payload with:  #include \"bpatch_rt.h\"")
        return

    # ---- validate args ----
    missing = []
    if not args.binary:  missing.append("binary")
    if not args.at:      missing.append("--at")
    if not args.payload: missing.append("--payload")
    if missing:
        ap.print_help()
        print()
        print(f"[!] Missing required arguments: {', '.join(missing)}")
        print(f"    Run  bpatch.py --list  to see available payloads.")
        sys.exit(1)

    # ---- parse + validate inputs ----
    try:
        target_va = int(args.at, 16)
    except ValueError:
        print(f"[!] Invalid address: {args.at!r}  (expected hex, e.g. 0x140001234)")
        sys.exit(1)

    binary_path  = Path(args.binary)
    payload_path = Path(args.payload)

    # If payload not found as given, try examples/ subdirectory automatically
    if not payload_path.exists():
        candidate = Path(__file__).parent / "examples" / payload_path.name
        if candidate.exists():
            print(f"[*] Payload not found at {payload_path}, using {candidate}")
            payload_path = candidate
        else:
            print(f"[!] Payload not found: {payload_path}")
            print(f"    Run  bpatch.py --list  to see available payloads.")
            sys.exit(1)

    if not binary_path.exists():
        print(f"[!] Binary not found: {binary_path}")
        sys.exit(1)

    if args.output:
        out = Path(args.output)
    else:
        suf = ".exe" if binary_path.suffix.lower() == ".exe" else ""
        out = binary_path.with_suffix(f".patched{suf}")

    # Warn if output would overwrite the input
    if out.resolve() == binary_path.resolve():
        print(f"[!] Output path is the same as input. Use -o to specify a different path.")
        sys.exit(1)

    inject(binary_path, target_va, payload_path, out)
    print(f"\n[+] Done. Patched binary: {out}")
    print(f"    Original is unchanged:  {binary_path}")


